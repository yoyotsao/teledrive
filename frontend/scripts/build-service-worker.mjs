// Bundles src/service-worker/index.ts into public/sw.js — the file the browser
// actually registers (main.tsx: navigator.serviceWorker.register('/sw.js'),
// served straight out of public/ by vite dev and by nginx in production).
//
// Why this exists: it did not, and public/sw.js was a hand-maintained COPY that
// had drifted badly from the TypeScript source. The source grew a 3-chunk
// lookahead, split-file preloading and accountId routing for multi-account
// drives; the copy that shipped had none of it — a 1-chunk lookahead and no
// accountId at all, so video for a linked account resolved against the primary
// client. Every fix written against src/service-worker/ since then was dead
// code. Generating the file removes the possibility of that drift.
//
// The output is committed, because `vite dev` serves public/ verbatim and never
// runs this script. Re-run it after editing the source:
//   node scripts/build-service-worker.mjs
//
// A service worker registered without { type: 'module' } is a CLASSIC script,
// so the bundle must be self-contained with no import/export left in it — hence
// bundle + iife.
import { build } from 'esbuild';
import { join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = fileURLToPath(new URL('.', import.meta.url));

await build({
  entryPoints: [join(__dirname, '..', 'src', 'service-worker', 'index.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  // Readable on purpose: this is the one script that gets debugged from the
  // browser's Application tab, where a source map would not be loaded.
  minify: false,
  banner: {
    js: '// GENERATED by scripts/build-service-worker.mjs from src/service-worker/index.ts.\n'
      + '// Do not edit — edit the TypeScript source and re-run the script.',
  },
  outfile: join(__dirname, '..', 'public', 'sw.js'),
});

console.log('Wrote public/sw.js');
